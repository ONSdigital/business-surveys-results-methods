def test_detect_outlier_winsorisation_component(
	winsorisation_component_test_input,
	winsorisation_component_test_output,
):
	"""Compare flags, weights, and adjusted returns for every row."""
	result = detect_outlier(
		df=winsorisation_component_test_input.assign(question_no=2),
		question_no_col="question_no",
		calibration_group_col="calibration_group_j",
		aux_col="xi",
		a_weight_col="ai",
		g_weight_col="gi",
		target_col="yi_2",
		l_value=15,
	)

	actual = result.rename(columns={
		"predicted_unit_value": "mu_i",
		"ratio_estimation_threshold": "ki",
		"adjusted_return": "yi*",
		"outlier_weight": "oi",
	})
	actual["mu_factor"] = actual["mu_i"] / actual["xi"]
	expected = winsorisation_component_test_output
	assert_frame_equal(
		actual[expected.columns].round(4),
		expected.round(4),
		check_dtype=False,
		atol=1e-4,
	)
