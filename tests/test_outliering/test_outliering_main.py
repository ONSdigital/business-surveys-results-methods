def test_detect_outlier_winsorisation_component(
	winsorisation_component_test_input,
	winsorisation_component_test_output,
):
	"""Compare flags, weights, and adjusted returns for every row."""
	result = detect_outlier(
		df=winsorisation_component_test_input,
		question_no_col="k",
		calibration_group_col="stratum",
		aux_col="x",
		a_weight_col="ah",
		g_weight_col="gk",
		target_col="y",
		l_value=15,
	)

	columns = {
		"stratum": "cell", "k": "k", "ruref": "ruref", "y": "y", "x": "x",
		"ah": "ah", "gk": "gk", "L": "L", "outlier_flag": "flag",
		"outlier_weight": "o_i_rat",
	}
	expected = winsorisation_component_test_output[list(columns.values())].rename(
		columns={reference: actual for actual, reference in columns.items()}
	)
	expected["adjusted_return"] = expected["y"] * expected["outlier_weight"]
	assert_frame_equal(
		result[expected.columns].round(4),
		expected.round(4),
		check_dtype=False,
		atol=1e-4,
	)
