def test_apply_winsorise_ratio(winsorise_component_test_input, winsorise_ratio_test_output):
	"""Test winsorisation for ratio estimation case."""
	result = winsorise(
		df=winsorise_component_test_input,
		calibration_group_col="calibration_group_j",
		aux_col="xi",
		a_weight_col="ai",
		g_weight_col="gi",
		target_col="yi_2",
		l_values_col="L_yi_2",
	)

	expected = winsorise_ratio_test_output
	assert_frame_equal(
		result[expected.columns].round(4),
		expected.round(4),
		check_dtype=False,
		atol=1e-4,
	)


