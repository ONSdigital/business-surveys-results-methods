def test_run_estimation(
        estimation_component_test_input,
        estimation_component_test_output,
        estimation_component_test_qa_output
    ):
    """run_estimation returns the correct weighted df and QA df."""
    weighted_df, qa_df = run_estimation(
        df=estimation_component_test_input,
        a_wgt_band_col="a_wt_band",
        g_wgt_band_col="g_wt_band",
        ru_col="ruref",
        univ_count_col="N",
        aux_cols=["turnover"],
        univ_aux_cols=["univ_turnover_sum"],
        incl_g_wts=True,
    )
    assert_frame_equal(weighted_df.round(4), estimation_component_test_output, check_dtype=False, atol=1e-4)
    assert_frame_equal(qa_df.round(4), estimation_component_test_qa_output, check_dtype=False, atol=1e-4)
