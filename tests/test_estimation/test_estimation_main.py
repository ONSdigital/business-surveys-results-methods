def test_run_estimation(component_input, expected_output, expected_qa_output):
    """run_estimation returns the correct weighted df and QA df."""
    weighted_df, qa_df = run_estimation(
        df=component_input,
        strata_col="cell_no",
        ru_col="ruref",
        univ_count_col="N",
        aux_col="x",
        univ_aux_col="sum_x",
        incl_g_wts=True,
    )
    assert_frame_equal(weighted_df.round(4), expected_output, check_dtype=False, atol=1e-4)
    assert_frame_equal(qa_df.round(4), expected_qa_output, check_dtype=False, atol=1e-4)
